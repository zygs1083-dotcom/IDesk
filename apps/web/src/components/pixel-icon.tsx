export function PixelIcon({
  name,
  fallback,
  className,
  ...props
}: SVGProps<SVGSVGElement> & {
  name: IconName;
  fallback?: ReactNode;
}) {
  return (
    <span className={className} data-ui="pixel-icon-pair" aria-hidden="true">
      <svg
        {...props}
        role="presentation"
        aria-hidden="true"
        className="pixel-icon"
        width="16"
        height="16"
        viewBox="0 0 16 16"
        fill="currentColor"
        shapeRendering="crispEdges"
      >
        {cells[name].map(([x, y, width, height]) => (
          <rect key={`${x}:${y}:${width}:${height}`} x={x} y={y} width={width} height={height} />
        ))}
      </svg>
      {fallback && <span className="pixel-icon-fallback">{fallback}</span>}
    </span>
  );
}

