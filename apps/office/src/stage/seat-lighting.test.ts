import { type Container, Graphics, Sprite, Texture } from "pixi.js";
import { expect, test } from "vitest";
import { lightCover, moveCoverLighting, registerCover, shadeCovers } from "./seat-lighting.ts";
import type { Stage } from "./stage.ts";

test("cover lighting shares ambient drawing and clips the seated lamp after movement", () => {
  const stage = {} as Stage;
  const cover = new Sprite(Texture.WHITE);
  cover.setSize(68, 44);
  cover.position.set(509, 265);
  const seat = { x: 543, y: 285 };
  registerCover(stage, seat, cover);
  const shade = new Graphics().rect(0, 0, 1672, 941).fill(0x1a2340);
  shade.alpha = 0.6;
  shade.blendMode = "multiply";
  const tint = new Graphics().rect(0, 0, 1672, 941).fill(0x1a2340);
  tint.alpha = 0.25;
  shadeCovers(stage, shade, tint);
  const light = cover.getChildAt<Container>(0);
  const ambient = light.getChildAt<Graphics>(0);
  expect(ambient.context).toBe(shade.context);
  expect(ambient.alpha).toBe(0.6);
  expect(ambient.blendMode).toBe("multiply");
  expect([ambient.x, ambient.y]).toEqual([-509, -265]);
  expect(light.mask).toBe(cover.getChildAt(1));
  const lamp = new Sprite(Texture.WHITE);
  lamp.position.set(543, 245);
  lamp.blendMode = "add";
  lightCover(stage, seat, lamp);
  const copy = light.getChildAt<Sprite>(2);
  expect([copy.x, copy.y]).toEqual([34, -20]);
  expect(copy.blendMode).toBe("add");
  lightCover(stage, { x: 800, y: 440 }, lamp);
  expect(copy.visible).toBe(false);
  cover.position.set(515, 269);
  moveCoverLighting(cover);
  expect([ambient.x, ambient.y]).toEqual([-515, -269]);
  shade.visible = false;
  shadeCovers(stage, shade, tint);
  expect(ambient.visible).toBe(false);
  cover.destroy({ children: true });
  shade.destroy();
  tint.destroy();
  lamp.destroy();
});
